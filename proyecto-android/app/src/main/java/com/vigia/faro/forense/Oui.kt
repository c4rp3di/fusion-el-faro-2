    private val TABLA: Map<String, String> by lazy {
        val m = HashMap<String, String>()
        for ((nombre, prefijos) in GRUPOS) {
            for (p in prefijos.split(' ')) if (p.length == 6) m[p] = nombre
        }
        m
    }

    private fun limpiar(mac: String?): String? {
        if (mac == null) return null
        val h = mac.replace(":", "").replace("-", "").uppercase()
        return if (h.length == 12 && h.all { it in '0'..'9' || it in 'A'..'F' }) h else null
    }

    /** True si el bit de «administrada localmente» está activo: la MAC no es la de fábrica (típico de móviles con privacidad). */
    fun esAleatoria(mac: String?): Boolean {
        val h = limpiar(mac) ?: return false
        // Los prefijos de máquinas virtuales conocidos también tienen el bit activo (52:54:00) y no son «privacidad».
        if (TABLA[h.substring(0, 6)] != null) return false
        val primero = h.substring(0, 2).toInt(16)
        return (primero and 0x02) != 0
    }

    fun buscar(mac: String?): String? {
        val h = limpiar(mac) ?: return null
        return TABLA[h.substring(0, 6)]
    }

    /** Los tres primeros octetos («aa:bb:cc»), para comparar fabricantes entre dos MAC. */
    fun prefijo(mac: String?): String? {
        val h = limpiar(mac) ?: return null
        return h.substring(0, 6)
    }
